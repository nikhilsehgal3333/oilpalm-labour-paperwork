"""Integrity of the published text: clean wording, and generated numbers that all have a source."""
import json
import re
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]
MANIFEST = ROOT / "results" / "manifest.json"
START, END = "<!-- RESULTS:START -->", "<!-- RESULTS:END -->"
TEXT = ["README.md", "NOTE.md", "DEVIATIONS.md", "LICENSE", "codebook.yaml", "pyproject.toml"]
needs_results = pytest.mark.skipif(not MANIFEST.exists(), reason="run run_all.py first")


def published_files():
    files = [ROOT / n for n in TEXT if (ROOT / n).exists()]
    for folder in ("src", "scripts", "tests", "data"):
        files += [p for p in (ROOT / folder).rglob("*") if p.suffix in {".py", ".csv", ".md"}]
    return files


def test_text_scan_clean():
    bad = []
    for path in published_files():
        text = path.read_text(encoding="utf-8")
        for word in (chr(0x2014), "Nikk" + "hil", "Co-Authored" + "-By"):
            if word in text:
                bad.append(f"{path.name}: {word!r}")
    assert not bad, bad


def block(name: str) -> str:
    text = (ROOT / name).read_text(encoding="utf-8")
    return text.split(START)[1].split(END)[0]


@needs_results
def test_note_and_readme_carry_the_same_results():
    assert block("NOTE.md") == block("README.md")
    assert "Generated by" in block("NOTE.md")


@needs_results
def test_numbers_in_results_block_come_from_manifest():
    known = {str(v) for v in json.loads(MANIFEST.read_text(encoding="utf-8")).values()}
    text = re.sub(r"\(results/[^)]*\)|\([^)]*\d{4}[^)]*\)", " ", block("README.md"))  # links, years in labels
    numbers = set(re.findall(r"\b\d+\b", text))
    assert numbers <= known, f"numbers without a source: {sorted(numbers - known)}"
