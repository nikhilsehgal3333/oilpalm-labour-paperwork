"""Render NOTE.md to a self-contained HTML page (figure embedded) and print it to NOTE.pdf with a
headless Chrome or Edge. Run after run_all.py.

    uv run python scripts/build_pdf.py
"""
import base64
import re
import shutil
import subprocess
import sys
from pathlib import Path

import markdown

ROOT = Path(__file__).resolve().parents[1]
CANDIDATES = [r"C:\Program Files\Google\Chrome\Application\chrome.exe",
              r"C:\Program Files (x86)\Microsoft\Edge\Application\msedge.exe",
              "google-chrome", "chromium", "msedge"]
CSS = """
@page { size: A4; margin: 20mm 18mm 20mm 18mm; }
body { font-family: Georgia, 'Times New Roman', serif; font-size: 10.5pt; line-height: 1.42;
       color: #111; max-width: 170mm; margin: 0 auto; }
h1 { font-size: 17pt; margin: 0 0 4pt 0; line-height: 1.2; }
h2 { font-size: 12pt; margin: 14pt 0 4pt 0; }
p { margin: 0 0 6pt 0; text-align: justify; hyphens: auto; }
table { border-collapse: collapse; font-size: 8pt; margin: 6pt 0 8pt 0; width: 100%; }
th, td { border-bottom: 0.5pt solid #bbb; padding: 2pt 3pt; text-align: left; vertical-align: top; }
th { border-bottom: 1pt solid #333; }
img { width: 100%; margin: 4pt 0; }
ol, ul { margin: 0 0 6pt 0; padding-left: 16pt; } li { margin-bottom: 3pt; }
em { font-style: italic; }
p.lead { text-align: left; }
"""


def browser() -> str:
    for c in CANDIDATES:
        if Path(c).exists() or shutil.which(c):
            return c
    raise SystemExit("no Chrome or Edge found")


def main() -> None:
    text = (ROOT / "NOTE.md").read_text(encoding="utf-8")
    text = text.replace("<!-- RESULTS:START -->", "").replace("<!-- RESULTS:END -->", "")
    text = re.sub(r"^\*Generated by .*?\*\s*$", "", text, flags=re.M)
    text = re.sub(r"^\|.*\|[ \t]*\n?", "", text, flags=re.M)  # the PDF shows the chart; the table stays in README

    def embed(match):
        data = base64.b64encode((ROOT / match.group(2)).read_bytes()).decode("ascii")
        return f'<img alt="{match.group(1)}" src="data:image/png;base64,{data}">'

    body = markdown.markdown(text, extensions=["tables"])
    body = body.replace("<p>", '<p class="lead">', 2)  # subtitle and byline, not justified
    body = re.sub(r'<img alt="([^"]*)" src="([^"]+\.png)"\s*/?>', embed, body)
    html = f"<!doctype html><html lang='en'><head><meta charset='utf-8'><title>Labour in the paperwork of India's oil palm push</title><style>{CSS}</style></head><body>{body}</body></html>"
    out_html = ROOT / "local" / "note.html"
    out_html.parent.mkdir(exist_ok=True)
    out_html.write_text(html, encoding="utf-8")
    pdf = ROOT / "NOTE.pdf"
    subprocess.run([browser(), "--headless=new", "--disable-gpu", "--no-pdf-header-footer",
                    f"--print-to-pdf={pdf}", out_html.as_uri()], check=True,
                   stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    print(pdf, pdf.stat().st_size, "bytes")


if __name__ == "__main__":
    sys.exit(main())
