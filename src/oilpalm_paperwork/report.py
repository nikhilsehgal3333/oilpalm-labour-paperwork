"""Figure, manifest of numbers, and the generated results block of the README and the note.

Every number in the README and NOTE.md results blocks comes from `results/manifest.json`, which this
module writes from the results files. Nothing in those blocks is typed by hand.
"""
from __future__ import annotations

import csv
import json
import re
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
from matplotlib.colors import ListedColormap  # noqa: E402

from .paths import CORPUS_CSV, RESULTS, ROOT

LEVEL_VALUE = {"absent": 0, "generic": 1, "explicit_palm": 2}
SHORT = {"nmeo_os_guidelines": "NMEO-Oilseeds guidelines (2024)",
         "pib_moafw_2021": "NMEO-OP approval, PIB (2021)",
         "ls_au2850_2025": "Lok Sabha answer AU2850 (2025)",
         "godrej_brsr_fy25": "Godrej Agrovet BRSR (FY25)",
         "patanjali_brsr_fy25": "Patanjali Foods BRSR (FY25)",
         "rspo_sattva": "RSPO and Sattva study (2023-24)"}
CODE_LABEL = {"L1a": "Growers", "L1b": "Hired workers", "L2": "Pay and price",
              "L3": "Recruitment", "L4": "Health and safety", "L5": "Social reproduction",
              "L6": "Voice", "E1": "Land and tenure", "E2": "Environment of work",
              "S1": "Standards"}
START, END = "<!-- RESULTS:START -->", "<!-- RESULTS:END -->"


def read_csv(path: Path) -> list[dict]:
    with open(path, encoding="utf-8", newline="") as handle:
        return list(csv.DictReader(handle))


def heatmap(matrix: list[dict], path: Path) -> Path:
    docs = list(dict.fromkeys(r["doc"] for r in matrix))
    codes = list(dict.fromkeys(r["code"] for r in matrix))
    grid = [[LEVEL_VALUE[next(r["level"] for r in matrix if r["doc"] == d and r["code"] == c)]
             for c in codes] for d in docs]
    fig, ax = plt.subplots(figsize=(10, 3.9), dpi=150)
    cmap = ListedColormap(["#f2f2f2", "#9ecae1", "#08519c"])
    ax.imshow(grid, cmap=cmap, vmin=0, vmax=2, aspect="auto")
    ax.set_xticks(range(len(codes)), [CODE_LABEL[c] for c in codes], rotation=35, ha="right", fontsize=8)
    ax.set_yticks(range(len(docs)), [SHORT.get(d, d) for d in docs], fontsize=8)
    ax.set_xticks([x - 0.5 for x in range(1, len(codes))], minor=True)
    ax.set_yticks([y - 0.5 for y in range(1, len(docs))], minor=True)
    ax.grid(which="minor", color="white", linewidth=2)
    ax.tick_params(which="minor", length=0)
    handles = [plt.Rectangle((0, 0), 1, 1, color=c) for c in cmap.colors]
    ax.legend(handles, ["absent", "generic (not tied to palm)", "explicit for oil palm"],
              loc="upper center", bbox_to_anchor=(0.5, -0.42), ncol=3, fontsize=8, frameon=False)
    ax.set_title("What the documents say about labour and environment in oil palm", fontsize=10)
    fig.tight_layout()
    path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(path, metadata={"Software": None})
    plt.close(fig)
    return path


def manifest(matrix: list[dict], passages: list[dict], counts: list[dict]) -> dict:
    docs = list(dict.fromkeys(r["doc"] for r in matrix))
    m = {"documents": len(docs), "codes": len(dict.fromkeys(r["code"] for r in matrix)),
         "cells": len(matrix), "candidates": sum(int(r["candidates"]) for r in counts),
         "coded_passages": len(passages),
         "checked_by_author": sum(p["checked_by_author"] == "yes" for p in passages)}
    for level in LEVEL_VALUE:
        m[f"cells_{level}"] = sum(r["level"] == level for r in matrix)
    for code in ("L1a", "L1b", "L5"):
        m[f"{code}_explicit_docs"] = sum(r["level"] == "explicit_palm" for r in matrix if r["code"] == code)
    labour = [r for r in matrix if r["code"] in ("L1b", "L2", "L3", "L4", "L5", "L6")
              and r["doc"].endswith("_brsr_fy25")]
    m["brsr_labour_cells"] = len(labour)
    m["brsr_labour_cells_generic"] = sum(r["level"] == "generic" for r in labour)
    m["deciding_checked"] = sum(r["deciding_checked_by_author"] == "yes" for r in matrix)
    m["deciding_total"] = sum(r["deciding_checked_by_author"] != "n/a" for r in matrix)
    return m


def results_block(m: dict, matrix: list[dict]) -> str:
    docs = list(dict.fromkeys(r["doc"] for r in matrix))
    codes = list(dict.fromkeys(r["code"] for r in matrix))
    mark = {"explicit_palm": "palm", "generic": "generic", "absent": "-"}
    lines = [START, "", "*Generated by `run_all.py` from `results/`. Do not edit by hand.*", "",
             f"- Documents: {m['documents']}; codes: {m['codes']}; cells: {m['cells']}.",
             f"- Candidate passages found by keyword: {m['candidates']}; passages coded: "
             f"{m['coded_passages']}, of which {m['checked_by_author']} checked by the author.",
             f"- Cells: {m['cells_explicit_palm']} explicit for oil palm, {m['cells_generic']} generic, "
             f"{m['cells_absent']} absent. Deciding passage checked by the author in "
             f"{m['deciding_checked']} of {m['deciding_total']} non-empty cells.",
             f"- Growers are named in an oil palm context in {m['L1a_explicit_docs']} of "
             f"{m['documents']} documents; hired workers in {m['L1b_explicit_docs']}; social "
             f"reproduction in {m['L5_explicit_docs']}.",
             f"- In the two BRSRs, {m['brsr_labour_cells_generic']} of {m['brsr_labour_cells']} cells on "
             "hired labour (hired workers, pay, recruitment, safety, social reproduction, voice) are "
             "generic: company-wide, not tied to oil palm.", "",
             "| Document | " + " | ".join(CODE_LABEL[c] for c in codes) + " |",
             "|---|" + "---|" * len(codes)]
    for d in docs:
        cells = [mark[next(r["level"] for r in matrix if r["doc"] == d and r["code"] == c)] for c in codes]
        lines.append(f"| {SHORT.get(d, d)} | " + " | ".join(cells) + " |")
    lines += ["", "![Presence matrix](results/presence_matrix.png)", "", END]
    return "\n".join(lines)


def fill(path: Path, block: str) -> None:
    if not path.exists():
        return
    text = path.read_text(encoding="utf-8")
    if START in text and END in text:
        text = re.sub(re.escape(START) + r".*?" + re.escape(END), lambda _: block, text, flags=re.S)
        path.write_text(text, encoding="utf-8", newline="\n")


def run() -> dict:
    matrix = read_csv(RESULTS / "presence_matrix.csv")
    passages = read_csv(RESULTS / "coded_passages.csv")
    counts = read_csv(RESULTS / "candidate_counts.csv")
    heatmap(matrix, RESULTS / "presence_matrix.png")
    m = manifest(matrix, passages, counts)
    (RESULTS / "manifest.json").write_text(json.dumps(m, indent=1, sort_keys=True) + "\n", encoding="utf-8")
    block = results_block(m, matrix)
    for name in ("README.md", "NOTE.md"):
        fill(ROOT / name, block)
    return m
