"""Build the results site (site/index.html) from NOTE.md and the results files. No JavaScript.

    uv run python site/build.py      (also called by run_all.py)
"""
import base64
import re
import shutil
from pathlib import Path

import markdown

ROOT = Path(__file__).resolve().parents[1]
SITE = ROOT / "site"
REPO = "https://github.com/nikhilsehgal3333/oilpalm-labour-paperwork"
CSS = """
:root { --bg:#fbfbf9; --fg:#1b1b1b; --muted:#5b5b5b; --line:#d9d9d4; --accent:#08519c; }
@media (prefers-color-scheme: dark) { :root { --bg:#141414; --fg:#e8e8e3; --muted:#a3a39c;
  --line:#3a3a36; --accent:#7fb3e6; } img.chart { background:#fff; border-radius:4px; } }
* { box-sizing: border-box; }
body { margin:0; background:var(--bg); color:var(--fg); font:16px/1.6 Georgia,'Times New Roman',serif; }
main { max-width: 820px; margin: 0 auto; padding: 32px 16px 64px; }
h1 { font-size: 1.9rem; line-height:1.2; margin: 0 0 .3rem; }
h2 { font-size: 1.25rem; margin: 2rem 0 .5rem; border-top:1px solid var(--line); padding-top:1.2rem; }
a { color: var(--accent); }
.bar { display:flex; flex-wrap:wrap; gap:.6rem 1.2rem; font: 14px/1.4 system-ui, sans-serif; margin: 1rem 0 1.5rem; }
.posture { font: 13px/1.5 system-ui, sans-serif; color: var(--muted); border-left:3px solid var(--line);
  padding: .4rem .8rem; margin: 1rem 0; }
.table-wrap { overflow-x:auto; }
table { border-collapse: collapse; font: 13px/1.4 system-ui, sans-serif; margin: .8rem 0; min-width: 640px; }
th, td { border-bottom: 1px solid var(--line); padding: 4px 6px; text-align:left; vertical-align: top; }
img { max-width: 100%; height:auto; }
footer { font: 13px/1.5 system-ui, sans-serif; color: var(--muted); margin-top: 3rem; }
"""


def build() -> Path:
    SITE.mkdir(exist_ok=True)
    text = (ROOT / "NOTE.md").read_text(encoding="utf-8")
    text = text.replace("<!-- RESULTS:START -->", "").replace("<!-- RESULTS:END -->", "")
    text = re.sub(r"^\*Generated by .*?\*\s*$", "", text, flags=re.M)
    title, rest = text.split("\n", 1)
    body = markdown.markdown(rest, extensions=["tables"])
    png = (ROOT / "results" / "presence_matrix.png").read_bytes()
    img = f'<img class="chart" alt="Presence matrix" src="data:image/png;base64,{base64.b64encode(png).decode()}">'
    body = re.sub(r'<img alt="[^"]*" src="results/presence_matrix\.png"\s*/?>', img, body)
    body = body.replace("<table>", '<div class="table-wrap"><table>').replace("</table>", "</table></div>")
    has_pdf = (ROOT / "NOTE.pdf").exists()
    if has_pdf:
        shutil.copyfile(ROOT / "NOTE.pdf", SITE / "NOTE.pdf")
    links = [f'<a href="{REPO}">Code and coded data on GitHub</a>',
             f'<a href="{REPO}/blob/main/results/coding_log.csv">Coding log</a>',
             f'<a href="{REPO}/blob/main/DEVIATIONS.md">Deviations from the plan</a>']
    if has_pdf:
        links.insert(0, '<a href="NOTE.pdf">Note as PDF</a>')
    html = (
        "<!doctype html><html lang='en'><head><meta charset='utf-8'>"
        "<meta name='viewport' content='width=device-width, initial-scale=1'>"
        "<title>Labour in the paperwork of India's oil palm push</title>"
        "<meta name='description' content='An independent desk study of how policy and corporate "
        "documents represent labour on India's oil palm frontier.'>"
        f"<style>{CSS}</style></head><body><main>"
        f"<h1>{title.lstrip('# ').strip()}</h1>"
        f"<div class='bar'>{' · '.join(links)}</div>"
        "<p class='posture'>An independent desk study by Nikhil Sehgal on public documents only. It is "
        "not an output of the University of Bonn, the PALMWORK project or any company named.</p>"
        f"{body}"
        "<footer>Built from the result files by <code>site/build.py</code>. Code: MIT licence. "
        "Excerpts from documents are short quotations with page references.</footer>"
        "</main></body></html>")
    out = SITE / "index.html"
    out.write_text(html, encoding="utf-8", newline="\n")
    return out


if __name__ == "__main__":
    print(build())
